// Helper: compute the current Heliocronic day count
export function heliocronDays(now = new Date()) {
  // The Great Ignition: 4.6 billion years before present (approximate)
  // Treat "present" for the epoch as Jan 1, 2000 12:00 UTC for stability
  const BILLION_YEARS_IN_DAYS = 365.25 * 1e9;
  const GREAT_IGNITION_DAYS_BEFORE_J2000 = 4.6 * BILLION_YEARS_IN_DAYS;
  const J2000 = new Date('2000-01-01T12:00:00Z').getTime();
  const daysSinceJ2000 = (now.getTime() - J2000) / (1000 * 60 * 60 * 24);
  return Math.floor(GREAT_IGNITION_DAYS_BEFORE_J2000 + daysSinceJ2000);
}

